"""Anki ``.apkg`` export.

An ``.apkg`` is a zip holding a legacy ``collection.anki2`` SQLite database and
a ``media`` manifest. This writes the smallest collection Anki 2.1 accepts on
import: one model, one deck, one note+card per Shellslatee card, using schema
version 11. No third-party dependency — ``sqlite3`` and ``zipfile`` are stdlib.

The legacy schema is deliberate: Anki still imports it, and it avoids the
schema-18 ``collection.anki21b`` protobuf complexity. If a future Anki drops
schema 11, point at the CSV export (``shellslatee cards export``) instead.
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
import time
import zipfile
from pathlib import Path

from . import cards

MODEL_ID = 1_700_000_000_001
DECK_ID = 1
DECK_NAME = "Shellslatee"
MODEL_NAME = "Shellslatee Basic"


def _checksum(text: str) -> int:
    return int(hashlib.sha1(text.encode("utf-8")).hexdigest()[:8], 16)


def _guid(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def _model(now_ms: int) -> dict:
    return {
        "id": MODEL_ID,
        "name": MODEL_NAME,
        "type": 0,
        "mod": now_ms,
        "usn": 0,
        "sortf": 0,
        "did": DECK_ID,
        "tmpls": [
            {
                "name": "Card 1",
                "ord": 0,
                "qfmt": "{{Front}}",
                "afmt": "{{FrontSide}}<hr id=answer>{{Back}}",
                "bqfmt": "",
                "bafmt": "",
                "did": None,
                "bfont": "",
                "bsize": 0,
            }
        ],
        "flds": [
            {"name": "Front", "ord": 0, "sticky": False, "rtl": False, "font": "Arial", "size": 20, "media": []},
            {"name": "Back", "ord": 1, "sticky": False, "rtl": False, "font": "Arial", "size": 20, "media": []},
        ],
        "css": ".card{font-family:Arial;font-size:20px;text-align:left;color:black;background:white}",
        "latexPre": "\\documentclass[12pt]{article}\\special{papersize=3in,5in}\\usepackage{amssymb,amsmath}"
        "\\pagestyle{empty}\\setlength{\\parindent}{0in}\\begin{document}",
        "latexPost": "\\end{document}",
        "tags": [],
        "vers": [],
    }


def _deck(now_ms: int) -> dict:
    return {
        "id": DECK_ID,
        "name": DECK_NAME,
        "mod": now_ms,
        "usn": 0,
        "desc": "Generated by Shellslatee",
        "dyn": 0,
        "collapsed": False,
        "browserCollapsed": False,
        "newToday": [0, 0],
        "revToday": [0, 0],
        "lrnToday": [0, 0],
        "timeToday": [0, 0],
        "conf": 1,
        "extendNew": 0,
        "extendRev": 0,
    }


